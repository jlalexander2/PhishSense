ALTER TABLE users ADD COLUMN study_group TEXT NOT NULL DEFAULT 'unassigned'
    CHECK (study_group IN ('unassigned', 'control', 'experimental'));
ALTER TABLE training_sessions ADD COLUMN study_group TEXT NOT NULL DEFAULT 'unassigned'
    CHECK (study_group IN ('unassigned', 'control', 'experimental'));
ALTER TABLE training_sessions ADD COLUMN algorithm_version TEXT;
ALTER TABLE training_sessions ADD COLUMN scenario_ids JSONB;
CREATE TABLE difficulty_evaluations (
    evaluation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES training_sessions(session_id),
    block_number INTEGER NOT NULL,
    response_ids INTEGER[] NOT NULL,
    algorithm_version TEXT NOT NULL,
    study_group TEXT NOT NULL,
    previous_difficulty TEXT NOT NULL,
    proposed_difficulty TEXT NOT NULL,
    applied_difficulty TEXT NOT NULL,
    accuracy DOUBLE PRECISION NOT NULL,
    median_response_time DOUBLE PRECISION NOT NULL,
    mean_confidence DOUBLE PRECISION NOT NULL,
    reason TEXT NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(session_id, block_number)
);
ALTER TABLE difficulty_evaluations ENABLE ROW LEVEL SECURITY;

-- Additive only; historical scenario fields and all research records stay intact.
ALTER TABLE training_scenarios ADD COLUMN training_context TEXT;
ALTER TABLE training_scenarios ADD COLUMN learning_objectives JSONB
    CHECK (learning_objectives IS NULL OR jsonb_typeof(learning_objectives) = 'array');
-- Shared key means mutually exclusive within a session; NULL means independent.
ALTER TABLE training_scenarios ADD COLUMN matched_pair_id TEXT
    CHECK (matched_pair_id IS NULL OR length(trim(matched_pair_id)) > 0);
-- Keep newly introduced content out of already-running older protocols.
ALTER TABLE training_scenarios ADD COLUMN introduced_in_version TEXT;
CREATE INDEX ON training_scenarios(matched_pair_id);
